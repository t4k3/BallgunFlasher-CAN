const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto'),assert=require('node:assert/strict');
const root=path.resolve(__dirname,'..');
const parse=file=>new Map(fs.readFileSync(path.join(root,file),'utf8').split(/\r?\n/).map(line=>line.match(/^(\d+)\s*,\s*(-?\d+)\s*,/)).filter(Boolean).map(m=>[Number(m[1]),Number(m[2])]));
const canonical=parse('FTD30/waz_nodo2.prm');
const experimental=parse('FTD30/waz_nodo2-current151-idstart101.prm');
assert.equal(canonical.size,1024);assert.equal(experimental.size,1024);
const changed=[...canonical].filter(([index,value])=>experimental.get(index)!==value).map(([index])=>index);
assert.deepEqual(changed,[62,63,238]);
assert.equal(experimental.get(62),151);
assert.equal(experimental.get(63),151);
assert.equal(experimental.get(238),101);
const bytes=fs.readFileSync(path.join(root,'FTD30/waz_nodo2-current151-idstart101.prm'));
assert.equal(crypto.createHash('sha256').update(bytes).digest('hex'),'cb18982d8de8456f911460afb9322da00bc170c3a3847831a80a4aa121829a76');
const internal=fs.readFileSync(path.join(root,'index.html'),'utf8');
const fleet=fs.readFileSync(path.join(root,'fleet.html'),'utf8');
assert.match(internal,/id="fparExperimentalBtn"/);
assert.match(internal,/P62=151[^<]*P63=151[^<]*P238=101/);
assert.match(internal,/waz_nodo2-current151-idstart101\.prm/);
assert.match(internal,/FPAR_EXPERIMENTAL_SHA = 'cb18982d8de8456f911460afb9322da00bc170c3a3847831a80a4aa121829a76'/);
assert.doesNotMatch(fleet,/current151|fparExperimental|P238=101/);
console.log('PASS FTD30 experimental internal set: only P62/P63/P238 change; canonical and Fleet remain separate');
